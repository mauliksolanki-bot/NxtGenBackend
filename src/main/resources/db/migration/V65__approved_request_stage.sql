UPDATE NXTGEN_SR_LOOKUP SET DISPLAY_ORDER = CASE LOOKUP_CODE
    WHEN 'Fulfillment' THEN 4 WHEN 'Delivery' THEN 5 WHEN 'Closed' THEN 6 END
WHERE LOOKUP_TYPE = 'STAGE' AND LOOKUP_CODE IN ('Fulfillment', 'Delivery', 'Closed');

INSERT INTO NXTGEN_SR_LOOKUP (LOOKUP_TYPE, LOOKUP_CODE, LOOKUP_LABEL, DISPLAY_ORDER, IS_ACTIVE)
SELECT 'STAGE', 'Approved', 'Approved', 3, 'Y'
WHERE NOT EXISTS (SELECT 1 FROM NXTGEN_SR_LOOKUP WHERE LOOKUP_TYPE = 'STAGE' AND LOOKUP_CODE = 'Approved');
