ALTER TABLE NXTGEN_SR_APPROVALS
    MODIFY COLUMN APPROVAL_PENDING_TO VARCHAR(200) NULL,
    ADD COLUMN COMMENTS LONGTEXT NULL,
    ADD COLUMN CREATED_AT DATETIME NULL;

UPDATE NXTGEN_SR_APPROVALS a JOIN NXTGEN_SR_MASTER s ON s.SR_ID = a.SR_ID
SET a.CREATED_AT = COALESCE(s.OPENED_AT, s.CRE_DATE, CURRENT_TIMESTAMP);

INSERT INTO NXTGEN_GRID (GRID_NAME, DATA_API, LOADING_MESSAGE, CRE_BY)
VALUES ('SR_APPROVERS_GRID', '/api/sr/{srId}/approvers', 'Loading approvers...', 'SYSTEM');

INSERT INTO NXTGEN_GRID_COLUMN
(GRID_ID, COLUMN_NAME, DATA_FIELD, WIDTH, DISPLAY_ORDER, IS_SORTABLE, IS_FILTERABLE, IS_HIDDEN, CRE_BY)
SELECT g.ID, c.column_label, c.data_field, c.column_width, c.column_order, 'Y', 'Y', 'N', 'SYSTEM'
FROM NXTGEN_GRID g JOIN (
    SELECT 'State' column_label, 'state' data_field, 190 column_width, 1 column_order
    UNION ALL SELECT 'Approver', 'approver', 280, 2
    UNION ALL SELECT 'Comments', 'comments', 360, 3
    UNION ALL SELECT 'Created', 'createdAt', 220, 4
) c ON 1 = 1
WHERE g.GRID_NAME = 'SR_APPROVERS_GRID';
