-- One request form per sub-category. Each form is a full copy of CREATE_SR_FORM plus a read-only
-- Subcategory field, so every sub-category can be changed independently in NXTGEN_FORM_FIELDS.
UPDATE NXTGEN_SVC_SUBCATEGORY SET FORM_NAME = CONCAT('SR_FORM_', ID) WHERE FORM_NAME IS NULL;

INSERT INTO NXTGEN_FORM (FORM_NAME, DATA_API, TEMPLATE_TYPE, CRE_BY)
SELECT s.FORM_NAME, '/api/sr', 'SR_FORM', 'SYSTEM'
FROM NXTGEN_SVC_SUBCATEGORY s
WHERE NOT EXISTS (SELECT 1 FROM NXTGEN_FORM f WHERE f.FORM_NAME = s.FORM_NAME);

INSERT INTO NXTGEN_FORM_FIELDS
(FORM_ID, TEMPLATE_TYPE, DISPLAY_ORDER, FIELD_NAME, FIELD_LABEL, DATA_FIELD, FIELD_TYPE,
 PLACEHOLDER, IS_MANDATORY, IS_READONLY, DEFAULT_VALUE, OPTIONS_SOURCE, IS_FULL_WIDTH, CRE_BY)
SELECT nf.ID, bf.TEMPLATE_TYPE,
       CASE WHEN bf.DISPLAY_ORDER >= 11 THEN bf.DISPLAY_ORDER + 1 ELSE bf.DISPLAY_ORDER END,
       bf.FIELD_NAME, bf.FIELD_LABEL, bf.DATA_FIELD, bf.FIELD_TYPE,
       bf.PLACEHOLDER, bf.IS_MANDATORY, bf.IS_READONLY, bf.DEFAULT_VALUE, bf.OPTIONS_SOURCE, bf.IS_FULL_WIDTH, 'SYSTEM'
FROM NXTGEN_FORM_FIELDS bf
         JOIN NXTGEN_FORM base ON base.ID = bf.FORM_ID AND base.FORM_NAME = 'CREATE_SR_FORM'
         JOIN NXTGEN_SVC_SUBCATEGORY s ON 1 = 1
         JOIN NXTGEN_FORM nf ON nf.FORM_NAME = s.FORM_NAME
WHERE NOT EXISTS (SELECT 1 FROM NXTGEN_FORM_FIELDS x WHERE x.FORM_ID = nf.ID);

INSERT INTO NXTGEN_FORM_FIELDS
(FORM_ID, TEMPLATE_TYPE, DISPLAY_ORDER, FIELD_NAME, FIELD_LABEL, DATA_FIELD, FIELD_TYPE,
 PLACEHOLDER, IS_MANDATORY, IS_READONLY, DEFAULT_VALUE, OPTIONS_SOURCE, IS_FULL_WIDTH, CRE_BY)
SELECT nf.ID, 'SR_FORM', 11, 'SUBCATEGORY', 'Subcategory', 'subcategory', 'TEXT',
       '', 'N', 'Y', NULL, NULL, 'N', 'SYSTEM'
FROM NXTGEN_SVC_SUBCATEGORY s
         JOIN NXTGEN_FORM nf ON nf.FORM_NAME = s.FORM_NAME
WHERE NOT EXISTS (SELECT 1 FROM NXTGEN_FORM_FIELDS x WHERE x.FORM_ID = nf.ID AND x.DATA_FIELD = 'subcategory');
