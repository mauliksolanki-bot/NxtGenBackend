-- Existing users require a real manager selection when next edited.
ALTER TABLE NXTGEN_USERS_MASTER ADD COLUMN MANAGER_ID BIGINT NULL;
CREATE INDEX IDX_USER_MANAGER ON NXTGEN_USERS_MASTER (MANAGER_ID);
ALTER TABLE NXTGEN_USERS_MASTER ADD CONSTRAINT FK_USER_MANAGER
    FOREIGN KEY (MANAGER_ID) REFERENCES NXTGEN_USERS_MASTER (ID);

INSERT INTO NXTGEN_ROLES (ROLE_NAME, DESCRIPTION, IS_ACTIVE)
SELECT 'MANAGER', 'Manages users and their reporting responsibilities.', 'Y'
WHERE NOT EXISTS (SELECT 1 FROM NXTGEN_ROLES WHERE UPPER(TRIM(ROLE_NAME)) = 'MANAGER');

INSERT INTO NXTGEN_FORM_FIELDS
(FORM_ID, TEMPLATE_TYPE, DISPLAY_ORDER, FIELD_NAME, FIELD_LABEL, DATA_FIELD, FIELD_TYPE,
 PLACEHOLDER, IS_MANDATORY, IS_READONLY, DEFAULT_VALUE, OPTIONS_SOURCE, CRE_BY)
SELECT f.ID, 'USER_FORM',
       (SELECT COALESCE(MAX(ff.DISPLAY_ORDER), 0) + 1 FROM NXTGEN_FORM_FIELDS ff WHERE ff.FORM_ID = f.ID),
       'MANAGER', 'Manager', 'manager', 'SEARCH', 'Search and select manager', 'Y', 'N', NULL, NULL, 'SYSTEM'
FROM NXTGEN_FORM f WHERE f.FORM_NAME IN ('CREATE_USER_FORM', 'EDIT_USER_FORM');
