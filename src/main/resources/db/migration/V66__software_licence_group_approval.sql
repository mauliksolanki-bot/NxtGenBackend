SET @licence_group_ddl = IF(EXISTS (SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'NXTGEN_SR_APPROVAL_CHECKS' AND COLUMN_NAME = 'APPROVER_GROUP_ID'),
    'SELECT 1', 'ALTER TABLE NXTGEN_SR_APPROVAL_CHECKS ADD COLUMN APPROVER_GROUP_ID BIGINT NULL');
PREPARE licence_group_statement FROM @licence_group_ddl;
EXECUTE licence_group_statement;
DEALLOCATE PREPARE licence_group_statement;

SET @licence_group_ddl = IF(EXISTS (SELECT 1 FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'NXTGEN_SR_APPROVALS' AND COLUMN_NAME = 'APPROVER_GROUP_ID'),
    'SELECT 1', 'ALTER TABLE NXTGEN_SR_APPROVALS ADD COLUMN APPROVER_GROUP_ID BIGINT NULL');
PREPARE licence_group_statement FROM @licence_group_ddl;
EXECUTE licence_group_statement;
DEALLOCATE PREPARE licence_group_statement;

UPDATE NXTGEN_SR_APPROVAL_CHECKS c
JOIN NXTGEN_GROUPS_ND_TEAMS g ON UPPER(TRIM(g.GRP_NAME)) = 'SOFTWARE LICENCE MANAGEMENT'
SET c.APPROVER_GROUP_ID = g.ID, c.APPROVER_ROLE = NULL
WHERE UPPER(TRIM(c.APPROVER_ROLE)) = 'SOFTWARE LICENCE MANAGER';

UPDATE NXTGEN_SR_APPROVALS a
JOIN NXTGEN_GROUPS_ND_TEAMS g ON UPPER(TRIM(g.GRP_NAME)) = 'SOFTWARE LICENCE MANAGEMENT'
SET a.APPROVER_GROUP_ID = g.ID, a.APPROVER_ROLE = NULL,
    a.APPROVER_USER_ID = NULL, a.APPROVAL_PENDING_TO = g.GRP_NAME
WHERE UPPER(TRIM(a.APPROVER_ROLE)) = 'SOFTWARE LICENCE MANAGER';

-- Remove the retired role and its assignments after the group routing is configured.
DELETE ur FROM NXTGEN_USER_ROLES ur JOIN NXTGEN_ROLES r ON r.ID = ur.ROLE_ID
WHERE UPPER(TRIM(r.ROLE_NAME)) = 'SOFTWARE LICENCE MANAGER'
AND EXISTS (SELECT 1 FROM NXTGEN_SR_APPROVAL_CHECKS WHERE APPROVER_GROUP_ID IS NOT NULL);

DELETE FROM NXTGEN_ROLES WHERE UPPER(TRIM(ROLE_NAME)) = 'SOFTWARE LICENCE MANAGER'
AND EXISTS (SELECT 1 FROM NXTGEN_SR_APPROVAL_CHECKS WHERE APPROVER_GROUP_ID IS NOT NULL);
