-- Populate assignee metadata for older approvals without changing their decisions.
UPDATE NXTGEN_SR_APPROVALS a
JOIN NXTGEN_SR_MASTER s ON s.SR_ID = a.SR_ID
JOIN NXTGEN_SR_APPROVAL_CHECKS c ON c.APPROVAL_LEVEL = a.APPROVAL_LEVEL
    AND c.IS_ACTIVE = 'Y'
    AND ((c.SUBCATEGORY IS NOT NULL AND c.SUBCATEGORY = s.SUBCATEGORY)
        OR (c.SUBCATEGORY IS NULL AND c.REQUEST_TYPE = s.REQUEST_TYPE))
LEFT JOIN NXTGEN_USERS_MASTER requester ON requester.USERNAME = s.OPENED_BY_USERNAME
LEFT JOIN NXTGEN_USERS_MASTER manager ON manager.ID = requester.MANAGER_ID
SET a.APPROVAL_NAME = c.APPROVAL_NAME,
    a.APPROVER_ROLE = c.APPROVER_ROLE,
    a.APPROVER_USER_ID = CASE WHEN UPPER(c.APPROVER_ROLE) = 'MANAGER' THEN manager.ID ELSE NULL END,
    a.APPROVAL_PENDING_TO = CASE WHEN UPPER(c.APPROVER_ROLE) = 'MANAGER' AND manager.ID IS NOT NULL
        THEN CONCAT(manager.EMPL_NM, ' (', manager.USERNAME, ')') ELSE c.APPROVAL_NAME END
WHERE a.APPROVER_ROLE IS NULL
AND (c.SUBCATEGORY IS NOT NULL OR NOT EXISTS (SELECT 1 FROM NXTGEN_SR_APPROVAL_CHECKS scoped
                                            WHERE scoped.SUBCATEGORY = s.SUBCATEGORY AND scoped.IS_ACTIVE = 'Y'));
