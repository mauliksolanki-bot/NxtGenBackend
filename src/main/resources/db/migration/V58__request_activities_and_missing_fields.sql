ALTER TABLE NXTGEN_SR_MASTER
    ADD COLUMN WATCH_LIST VARCHAR(1000) NULL,
    ADD COLUMN BACKORDERED BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN ORDER_GUIDE VARCHAR(200) NULL;

CREATE TABLE NXTGEN_SR_ACTIVITY (
    ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    SR_ID VARCHAR(50) NOT NULL,
    ACTIVITY_TYPE VARCHAR(50) NOT NULL,
    AUTHOR VARCHAR(200) NOT NULL,
    BODY LONGTEXT NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    INDEX IDX_SR_ACTIVITY (SR_ID, CREATED_AT, ID),
    CONSTRAINT FK_SR_ACTIVITY_SR FOREIGN KEY (SR_ID) REFERENCES NXTGEN_SR_MASTER (SR_ID)
);

-- Preserve existing notes and attachments in the new journal.
INSERT INTO NXTGEN_SR_ACTIVITY (SR_ID, ACTIVITY_TYPE, AUTHOR, BODY, CREATED_AT)
SELECT c.SR_ID, 'Work notes', COALESCE(s.OPENED_BY, s.OPENED_BY_USERNAME, 'System'), c.WORK_NOTES,
       COALESCE(s.UPD_DATE, s.CRE_DATE, CURRENT_TIMESTAMP)
FROM NXTGEN_SR_COMMENTS c JOIN NXTGEN_SR_MASTER s ON s.SR_ID = c.SR_ID
WHERE c.WORK_NOTES IS NOT NULL AND TRIM(c.WORK_NOTES) <> '';

INSERT INTO NXTGEN_SR_ACTIVITY (SR_ID, ACTIVITY_TYPE, AUTHOR, BODY, CREATED_AT)
SELECT SR_ID, 'Attachment uploaded', COALESCE(UPLOADED_BY, 'System'),
       CONCAT(FILE_NAME, '\n', FILE_SIZE, ' bytes'), COALESCE(UPLOADED_AT, CURRENT_TIMESTAMP)
FROM NXTGEN_SR_ATTACHMENTS;

INSERT INTO NXTGEN_FORM_FIELDS
(FORM_ID, TEMPLATE_TYPE, DISPLAY_ORDER, FIELD_NAME, FIELD_LABEL, DATA_FIELD, FIELD_TYPE,
 PLACEHOLDER, IS_MANDATORY, IS_READONLY, DEFAULT_VALUE, IS_FULL_WIDTH, CRE_BY)
SELECT f.ID, 'SR_FORM', v.ord, v.fname, v.label, v.dfield, v.ftype,
       '', 'N', 'N', v.defval, 'N', 'SYSTEM'
FROM NXTGEN_FORM f JOIN (
    SELECT 13 ord, 'WATCH_LIST' fname, 'Watch list' label, 'watchList' dfield, 'TEXT' ftype, '' defval
    UNION ALL SELECT 14, 'BACKORDERED', 'Backordered', 'backordered', 'CHECKBOX', 'false'
    UNION ALL SELECT 16, 'ORDER_GUIDE', 'Order Guide', 'orderGuide', 'TEXT', ''
) v ON 1 = 1
WHERE (f.FORM_NAME = 'CREATE_SR_FORM' OR f.FORM_NAME LIKE 'SR_FORM_%')
AND NOT EXISTS (SELECT 1 FROM NXTGEN_FORM_FIELDS x WHERE x.FORM_ID = f.ID AND x.DATA_FIELD = v.dfield);

UPDATE NXTGEN_FORM_FIELDS SET DISPLAY_ORDER = 18
WHERE DATA_FIELD = 'subcategory' AND TEMPLATE_TYPE = 'SR_FORM';
