FROM NXTGEN_GRID g JOIN (
    SELECT 'Requested Item' label, 'number' field, 170 width, 1 position
    UNION ALL SELECT 'Approval', 'approvalName', 280, 2
    UNION ALL SELECT 'State', 'state', 150, 3
    UNION ALL SELECT 'Approver', 'approver', 240, 4
    UNION ALL SELECT 'Comments', 'comments', 300, 5
    UNION ALL SELECT 'Created', 'createdAt', 200, 6
) c ON 1 = 1 WHERE g.GRID_NAME = 'MY_APPROVALS_GRID'
AND NOT EXISTS (SELECT 1 FROM NXTGEN_GRID_COLUMN existing
                WHERE existing.GRID_ID = g.ID AND existing.DATA_FIELD = c.field);
